#!/usr/bin/env python3
"""
generate_kernels.py — expand CONSTRUCTS x CONTEXTS (kernel_lib.py) into one
.cu source file per (Z,K) pair, plus source metadata JSON.

7 constructs x 6 contexts = 42 source files. Each file contains exactly one
__global__ kernel plus a minimal host main() so nvcc emits a complete
binary. Compilation (varying ptxas opt level / arch / toolkit on top of
these 42 fixed sources) is done separately by compile_matrix.py.

Usage:
    python3 generate_kernels.py --out-dir kernels/generated --meta-dir kernels/metadata
    python3 generate_kernels.py --only Z5 K2   # single pair, for quick iteration
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from kernel_lib import CONSTRUCTS, CONTEXTS, render_kernel


HEADER = (
    "// AUTO-GENERATED by robustness_study/scripts/generate_kernels.py — do not edit by hand.\n"
    "// Construct: {construct_id} ({construct_name}) x Context: {context_id} ({context_name})\n"
    "// Context based on: {based_on}\n"
    "\n"
    "#include <stdint.h>\n"
    "#include <cuda_runtime.h>\n"
    "\n"
)


def make_main(fname: str, context) -> str:
    """Minimal host launcher matching this context's parameter list."""
    if context.id in ("K0", "K1", "K2"):
        return (
            "int main() {\n"
            "    uint32_t *d_out;\n"
            "    cudaMalloc(&d_out, sizeof(uint32_t));\n"
            f"    {fname}<<<1, {context.block}>>>(d_out);\n"
            "    cudaDeviceSynchronize();\n"
            "    cudaFree(d_out);\n"
            "    return 0;\n"
            "}\n"
        )
    if context.id == "K3":
        return (
            "int main() {\n"
            "    float *d_in, *d_out;\n"
            "    cudaMalloc(&d_in, 256 * sizeof(float));\n"
            "    cudaMalloc(&d_out, sizeof(float));\n"
            f"    {fname}<<<1, {context.block}>>>(d_in, d_out, 256);\n"
            "    cudaDeviceSynchronize();\n"
            "    cudaFree(d_in); cudaFree(d_out);\n"
            "    return 0;\n"
            "}\n"
        )
    if context.id == "K4":
        return (
            "int main() {\n"
            "    float *dA, *dB, *dC;\n"
            "    cudaMalloc(&dA, 16 * 16 * sizeof(float));\n"
            "    cudaMalloc(&dB, 16 * 16 * sizeof(float));\n"
            "    cudaMalloc(&dC, 16 * 16 * sizeof(float));\n"
            f"    {fname}<<<1, {context.block}>>>(dA, dB, dC, 16, 16, 16);\n"
            "    cudaDeviceSynchronize();\n"
            "    cudaFree(dA); cudaFree(dB); cudaFree(dC);\n"
            "    return 0;\n"
            "}\n"
        )
    if context.id == "K5":
        return (
            "int main() {\n"
            "    float *dq, *dk, *dout;\n"
            "    cudaMalloc(&dq, 32 * sizeof(float));\n"
            "    cudaMalloc(&dk, 32 * sizeof(float));\n"
            "    cudaMalloc(&dout, sizeof(float));\n"
            f"    {fname}<<<1, {context.block}>>>(dq, dk, dout);\n"
            "    cudaDeviceSynchronize();\n"
            "    cudaFree(dq); cudaFree(dk); cudaFree(dout);\n"
            "    return 0;\n"
            "}\n"
        )
    raise ValueError(f"no main() template for context {context.id}")


def generate_one(zid: str, kid: str, out_dir: Path, meta_dir: Path) -> dict:
    construct = CONSTRUCTS[zid]
    context = CONTEXTS[kid]
    fname, kernel_src = render_kernel(construct, context)

    src = HEADER.format(
        construct_id=construct.id, construct_name=construct.name,
        context_id=context.id, context_name=context.name,
        based_on=context.based_on,
    ) + kernel_src + "\n" + make_main(fname, context)

    src_path = out_dir / f"{zid.lower()}_{kid.lower()}.cu"
    src_path.write_text(src, encoding="utf-8", newline="\n")

    src_hash = hashlib.sha256(src.encode("utf-8")).hexdigest()
    meta = {
        "construct_id": construct.id,
        "construct_name": construct.name,
        "construct_role": construct.role,
        "expected_structural_requirement": construct.expected_structural_requirement,
        "context_id": context.id,
        "context_name": context.name,
        "context_based_on": context.based_on,
        "block_threads": context.block,
        "sbuf_nwords": context.nwords,
        "sbuf_elem_type": context.elem,
        "kernel_function_name": fname,
        "source_file": str(src_path.as_posix()),
        "source_hash_sha256": src_hash,
    }
    meta_path = meta_dir / f"{zid.lower()}_{kid.lower()}.json"
    meta_path.write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return meta


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default="kernels/generated")
    ap.add_argument("--meta-dir", default="kernels/metadata")
    ap.add_argument("--only", nargs=2, metavar=("Z_ID", "K_ID"), default=None,
                     help="generate only one (construct, context) pair")
    args = ap.parse_args()

    out_dir = Path(args.out_dir)
    meta_dir = Path(args.meta_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    meta_dir.mkdir(parents=True, exist_ok=True)

    pairs = [tuple(args.only)] if args.only else [
        (z, k) for z in CONSTRUCTS for k in CONTEXTS
    ]

    generated = []
    for zid, kid in pairs:
        if zid not in CONSTRUCTS:
            print(f"ERROR: unknown construct {zid}", file=sys.stderr)
            sys.exit(1)
        if kid not in CONTEXTS:
            print(f"ERROR: unknown context {kid}", file=sys.stderr)
            sys.exit(1)
        meta = generate_one(zid, kid, out_dir, meta_dir)
        generated.append(meta)
        print(f"  generated {meta['source_file']}  ({meta['kernel_function_name']})")

    print(f"\n{len(generated)} kernel source file(s) generated.")

    # Sanity: every generated source file must be unique and every function
    # name unique — catches a template bug immediately rather than downstream.
    names = [m["kernel_function_name"] for m in generated]
    if len(names) != len(set(names)):
        print("ERROR: duplicate kernel function names generated!", file=sys.stderr)
        sys.exit(1)
    hashes = [m["source_hash_sha256"] for m in generated]
    if len(hashes) != len(set(hashes)) and len(generated) > 1:
        print("WARNING: two different (Z,K) pairs produced byte-identical source "
              "— expected only for Z0 (no-scrub) across different... actually "
              "never expected since context bodies differ; investigate.", file=sys.stderr)


if __name__ == "__main__":
    main()
