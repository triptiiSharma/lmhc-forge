#!/usr/bin/env python3
"""
test_nvdisasm_parser.py — tests for the independent nvdisasm/JSON parsing
path, using real JSON fixtures from both CUDA 12.8 and CUDA 13.3
(tests/fixtures_nvdisasm/), generated by actually running nvdisasm -c -json
on real compiled cubins from this study's corpus, not synthesized.
"""

import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "scripts"))
from nvdisasm_parser import parse_nvdisasm_json, validate_schema, demangle_simple
from classify_binary import classify_kernel

FIXTURES = Path(__file__).parent / "fixtures_nvdisasm"


def load(name):
    return json.loads((FIXTURES / name).read_text(encoding="utf-8"))


class TestSchemaValidation(unittest.TestCase):
    def test_real_cuda128_schema_valid(self):
        ok, reason = validate_schema(load("z0_k0_cuda128.json"))
        self.assertTrue(ok, reason)

    def test_real_cuda133_schema_valid(self):
        ok, reason = validate_schema(load("z5_k2_cuda133.json"))
        self.assertTrue(ok, reason)

    def test_malformed_top_level_rejected(self):
        ok, reason = validate_schema({"not": "a list"})
        self.assertFalse(ok)
        self.assertIn("2-element list", reason)

    def test_wrong_length_list_rejected(self):
        ok, reason = validate_schema([{}, [], "extra"])
        self.assertFalse(ok)


class TestRealCuda128Fixtures(unittest.TestCase):
    def test_absent_negative_control(self):
        """z0_k0: no scrub, no shared buffer touched at all -> ABSENT."""
        functions, err = parse_nvdisasm_json(load("z0_k0_cuda128.json"))
        self.assertIsNone(err)
        feat = functions["kernel_z0_k0"]
        self.assertEqual(feat.shared_store_count, 0)
        self.assertEqual(feat.zero_shared_store_count, 0)
        result = classify_kernel(feat)
        self.assertEqual(result.category, "ABSENT")

    def test_full_signature_hardened(self):
        """z5_k2, sm_89, O3: cross-checked against the cuobjdump/text-parser
        result from Phase 4 (store@212 < membar@214 < bar@215 < exit@216 in
        the text-line numbering) -- same ordering property must hold here,
        independently, in the JSON instruction-index numbering."""
        functions, err = parse_nvdisasm_json(load("z5_k2_sm89_O3_cuda128.json"))
        self.assertIsNone(err)
        feat = functions["kernel_z5_k2"]
        self.assertGreater(feat.zero_shared_store_count, 0)
        self.assertEqual(feat.membar_cta_count, 1)
        self.assertGreaterEqual(feat.bar_sync_count, 1)
        self.assertLess(feat.last_zero_store_index, feat.first_membar_cta_index)
        self.assertLess(feat.first_membar_cta_index, feat.last_bar_sync_index)
        result = classify_kernel(feat)
        self.assertEqual(result.category, "FULL_SIGNATURE")

    def test_indirect_zero_store_o0_matches_text_parser_finding(self):
        """z2_k0, sm_89, O0: the exact artifact manually traced in Phase 4
        via the cuobjdump/text parser, which found 5 indirect zero-stores,
        0 direct. This independently re-derives the same fact via a
        completely different parsing path (structured JSON, not regex over
        text) -- this is the real cross-tool check, not just a schema test."""
        functions, err = parse_nvdisasm_json(load("z2_k0_sm89_O0_cuda128.json"))
        self.assertIsNone(err)
        feat = functions["kernel_z2_k0"]
        self.assertEqual(feat.zero_shared_store_direct_count, 0)
        self.assertEqual(feat.zero_shared_store_indirect_count, 5)
        self.assertEqual(feat.zero_shared_store_count, 5)
        # Z2 = volatile, no fence, no barrier in K0 context -> STORE_ONLY
        result = classify_kernel(feat)
        self.assertEqual(result.category, "STORE_ONLY")


class TestRealCuda133Fixture(unittest.TestCase):
    def test_full_signature_hardened_cuda133(self):
        functions, err = parse_nvdisasm_json(load("z5_k2_cuda133.json"))
        self.assertIsNone(err)
        feat = functions["kernel_z5_k2"]
        result = classify_kernel(feat)
        self.assertEqual(result.category, "FULL_SIGNATURE")


class TestDemangle(unittest.TestCase):
    def test_matches_sass_parser_algorithm(self):
        self.assertEqual(demangle_simple("_Z12kernel_z0_k0Pj"), "kernel_z0_k0")
        self.assertEqual(demangle_simple("_Z12kernel_z5_k2Pj"), "kernel_z5_k2")


class TestParserNeverCoercesFailureToPass(unittest.TestCase):
    def test_missing_required_key_becomes_unsupported_not_full_signature(self):
        from nvdisasm_parser import extract_features
        feat = extract_features({"function-name": "_Z4testv"})  # missing sass-instructions
        self.assertTrue(feat.unsupported_records)
        result = classify_kernel(feat)
        self.assertNotEqual(result.category, "FULL_SIGNATURE")

    def test_bad_instruction_record_recorded_not_silently_dropped(self):
        from nvdisasm_parser import extract_features
        feat = extract_features({
            "function-name": "_Z4testv",
            "sass-instructions": [
                {"opcode": "STS", "operands": "[R0],RZ"},
                {"operands": "no opcode here"},  # malformed
                {"opcode": "EXIT"},
            ],
        })
        self.assertTrue(any("missing 'opcode'" in w for w in feat.unsupported_records))
        self.assertEqual(feat.instruction_count, 3)


if __name__ == "__main__":
    unittest.main()
